// The two reset endpoints need very different budgets, because the limiter
// counts *every* request and keys on client IP.
//
// forgot-password answers identically whether or not the account exists, so
// there is no "success" to clear the bucket against and it only decays with
// time. At the tight login budget that means 10 requests locks every resident
// in the building out of self-service for a quarter of an hour - and this is a
// residential intercom, so the whole block very often shares one NAT address.
// Nothing is gained by being stingy here: the response cannot enumerate
// accounts, and without the emailed token it cannot change a password. Its
// only abuse is mail volume, and that is bounded by the number of real
// addresses already registered.
const forgotRequestLimit = loginRateLimit({
  max: 30,
  windowMs: 15 * 60 * 1000,
  message: "Too many reset requests. Try again in a few minutes.",
});

