/**
 * Resolves one "email or phone" field to a resident.
 *
 * Phone formatting is the reason this exists: the column holds whatever
 * punctuation the person typed, so matching it literally means "+65 9001 0001"
 * and "6590010001" are different accounts. Candidates handle that, and when
 * they match more than one row we refuse instead of picking - guessing here
 * would let someone who knows a shared unit number sign in as a neighbour.
 */
function findResidentByIdentifier(
  db: Database.Database,
  identifier: string,
): { resident?: any; error?: string; status?: number } {
  const ident = identifier.trim();
  if (!ident) return { error: "Enter your email or phone number", status: 400 };

  if (isPhoneLike(ident)) {
    const candidates = phoneCandidates(ident);
    const rows = candidates.length
      ? (db
          .prepare(
            `SELECT * FROM residents WHERE phone_norm IN (${candidates.map(() => "?").join(",")})`,
          )
          .all(...candidates) as any[])
      : [];
    if (rows.length > 1) {
      return {
        error: "That phone number matches more than one account. Sign in with your email instead.",
        status: 409,
      };
    }
    if (rows.length === 1) return { resident: rows[0] };
  }

  const byEmail = db
    .prepare("SELECT * FROM residents WHERE lower(email) = lower(?)")
    .get(ident) as any;
  if (byEmail) return { resident: byEmail };
  return { error: "Invalid credentials", status: 401 };
}

/** The same resolution for an admin, so the portal takes a cell or an email. */
function findAdminByIdentifier(
  db: Database.Database,
  identifier: string,
): { admin?: any; error?: string; status?: number } {
  const ident = identifier.trim();
  if (!ident) return { error: "Enter your email or phone number", status: 400 };

  if (isPhoneLike(ident)) {
    const candidates = phoneCandidates(ident);
    const rows = candidates.length
      ? (db
          .prepare(
            `SELECT * FROM admins WHERE phone_norm IN (${candidates.map(() => "?").join(",")})`,
          )
          .all(...candidates) as any[])
      : [];
    if (rows.length > 1) {
      return {
        error: "That phone number matches more than one admin account. Use your email address.",
        status: 409,
      };
    }
    if (rows.length === 1) return { admin: rows[0] };
  }

  const byEmail = db.prepare("SELECT * FROM admins WHERE lower(email) = lower(?)").get(ident) as any;
  if (byEmail) return { admin: byEmail };
  return { error: "Invalid credentials", status: 401 };
}

/**
 * Checks a phone is not already held, in the normalised form.
 *
 * Scoped to one table on purpose. Login resolves an identifier against
 * residents and then admins, never both, so a number in both tables cannot
 * produce a wrong-account login - and the same person is legitimately both:
 * an admin who lives in the building is also a resident, with one number.
 * Forcing them to differ would mean inventing a second number for someone who
 * only owns one.
 *
 * The formatted string is not enough to compare either: "555-0100" and
 * "+1 555 0100" are one number typed twice, and the UNIQUE index on phone_norm
 * is what actually keeps them out of the table. The explicit check still runs
 * first so the caller gets a 409 with a readable message instead of a raw
 * SQLITE_CONSTRAINT from the INSERT.
 */
function phoneTaken(
  db: Database.Database,
  table: "residents" | "admins",
  phoneNorm: string | null,
  exceptId?: string,
): boolean {
  if (!phoneNorm) return false;
  const row = exceptId
    ? db.prepare(`SELECT id FROM ${table} WHERE phone_norm = ? AND id != ?`).get(phoneNorm, exceptId)
    : db.prepare(`SELECT id FROM ${table} WHERE phone_norm = ?`).get(phoneNorm);
  return !!row;
}

/**
 * A password handed to a resident or admin by an admin who forgot theirs.
 *
 * 16 characters from a 57-symbol alphabet is about 95 bits, and the alphabet
 * drops 0/O/1/l/I so it survives being read down a hallway and typed back in.
 */
function generateTempPassword(): string {
  const alphabet = "ABCDEFGHJKLMNPQRSTUVWXYZabcdefghijkmnopqrstuvwxyz23456789";
  let core = "";
  for (let i = 0; i < 16; i++) {
    core += alphabet[randomInt(alphabet.length)];
  }
  return `${core.slice(0, 4)}-${core.slice(4, 10)}-${core.slice(10)}`;
}

/** Where a reset link should point, per account type. */
function resetLinkFor(config: Config, accountType: "resident" | "admin", token: string): string {
  const base = config.publicBaseUrl.replace(/\/+$/, "");
  return `${base}/${accountType === "admin" ? "admin" : "resident"}/?token=${encodeURIComponent(token)}`;
}

